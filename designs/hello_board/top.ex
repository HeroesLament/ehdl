  # Serial diagnostic reporter (US1 FTDI). Streams six sticky latches as an ASCII
  # line `b0b1b2b3b4b5\r\n` at 115200 8N1 so the host can read the device's
  # internal state over /dev/cu.usbserial-* — no logic analyzer needed.
  # Column order (b0..b5):
  #   b0 = lat_dn_high   (raw D- was EVER high)
  #   b1 = lat_raw_k     (a raw K was EVER seen)
  #   b2 = lat_rx_active (PHY EVER declared a packet)
  #   b3 = lat_pkt_end   (a packet EVER passed CRC16)
  #   b4 = lat_accept    (a token EVER accepted)
  #   b5 = lat_tx_ran    (TX FSM EVER ran)
  # Serial diagnostic reporter (US1 FTDI) @ 9600 baud. Streams six sticky latches
  # as an ASCII line `b0b1b2b3b4b5\r\n` so the host reads device state over
  # /dev/cu.usbserial-*. 9600 (not 115200) avoids the FTDI RX-FIFO overrun that
  # stalls the link at high rates. Column order (b0..b5):
