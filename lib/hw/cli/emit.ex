defmodule Hw.CLI.Emit do
  @moduledoc "`ehdl emit`: a design to Verilog."

  use Cheer.Command

  alias Hw.CLI.Target

  command "emit" do
    about "Emit a design as Verilog"

    argument :design, help: "Design file (blinky.ex) or, in a Mix project, module"
    option :top, value_name: "MODULE", help: "Top component, when the design has several"
    option :out, short: :o, value_name: "FILE", help: "Output file, or - for stdout [default: <design>.v]"
    option :force, type: :boolean, help: "Overwrite a Verilog file ehdl did not write"
  end

  @impl Cheer.Command
  def run(args, _raw) do
    {_top, path} = emit(args)
    unless path == "-", do: IO.puts(path)
    :ok
  end

  @doc """
  Emit the design the arguments name. Returns the top module and the path
  written (`"-"` when the Verilog went to stdout).
  """
  @spec emit(map()) :: {module(), String.t()}
  def emit(args) do
    target = Target.load(args[:design])
    top = Target.top(target, args[:top])
    verilog = header(top) <> Hw.compile!(top)
    path = args[:out] || Target.stem(target, top) <> ".v"

    case path do
      "-" ->
        IO.write(verilog)

      _ ->
        unless args[:force], do: guard_overwrite(path)
        File.write!(path, verilog)
    end

    {top, path}
  end

  @marker "// Generated by ehdl"

  defp header(top), do: "#{@marker} from #{inspect(top)}. Edits are lost on the next emit.\n"

  # A hand-written blinky.v beside blinky.ex must not be replaced silently.
  defp guard_overwrite(path) do
    case File.open(path, [:read], &IO.read(&1, :line)) do
      {:ok, line} when is_binary(line) ->
        unless String.starts_with?(line, @marker) do
          Hw.CLI.fail!("#{path} exists and was not written by ehdl; pass -o FILE or --force")
        end

      _ ->
        :ok
    end
  end
end
