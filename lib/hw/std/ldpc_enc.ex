  @moduledoc """
  OcuSync LDPC encoder, n = 648, R = 1/2, Z = 27 (802.11n dual-diagonal
  prototype). GENERATED by `scripts/gen_ldpc_enc.exs`; edit the generator,
  not this file.

  Bit-exact twin of `OcuSync.Phy.Ldpc.encode/2` (nervezynq/ocusync) and of
  the model in `test/ldpc_enc_test.exs`.

  Takes the 12 info blocks of a codeword (27 bits each, bit r = info bit
  27 j + r) on `in_v` while `in_ready`, echoes each to the output at once
  (`out_idx` = j), then:

  * edge pass, one prototype edge per cycle (63 cycles + 1 drain):
    lambda_i ^= rotr(s_j, h_ij), one log-staged 27-bit rotator, pipelined
    one stage (one-hot row select `wen`, rotated block `rv_q`);
  * p0 = xor of the 12 lambdas (12 cycles), out as block 12;
  * p_1 = lambda_0 ^ term_0, p_(i+1) = lambda_i ^ term_i ^ p_i (11
    cycles), out as blocks 13..23. term_i is the fixed shift of p0 in the
    first parity column (wiring, no mux).

